def clean_and_parse_llm_json(raw_content: str, thinking_content: str = "") -> List[Transaccion]:
    """
    Robust JSON parser for local LLM structured outputs.
    Handles:
    - Empty or whitespace responses (returns empty list).
    - Reasoning model thinking tokens (<think>...</think> or separate thinking field).
    - Markdown code fences (```json ... ```).
    - Malformed responses or trailing text.
    """
    candidate = (raw_content or "").strip()

    # 1. If content is empty, check if JSON was emitted inside thinking
    if not candidate and thinking_content:
        match_think = re.search(r"(\{[\s\S]*\"transacciones\"[\s\S]*\})", thinking_content)
        if match_think:
            candidate = match_think.group(1).strip()

    if not candidate:
        return []

    # 2. Strip <think>...</think> tags if present in main content
    candidate = re.sub(r"<think>[\s\S]*?</think>", "", candidate).strip()

    # 3. Strip Markdown code blocks if present
    if "```" in candidate:
        code_block_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", candidate)
        if code_block_match:
            candidate = code_block_match.group(1).strip()

    # 4. Extract outermost JSON object { ... } or array [ ... ]
    obj_match = re.search(r"(\{[\s\S]*\})", candidate)
    if obj_match:
        candidate = obj_match.group(1).strip()
    else:
        arr_match = re.search(r"(\[[\s\S]*\])", candidate)
        if arr_match:
            candidate = arr_match.group(1).strip()

    # 5. Attempt direct JSON parsing
    try:
        data = json.loads(candidate)
        tx_list: List[Transaccion] = []

        if isinstance(data, dict):
            if "transacciones" in data and isinstance(data["transacciones"], list):
                for item in data["transacciones"]:
                    if isinstance(item, dict):
                        try:
                            tx = Transaccion.model_validate(item)
                            tx_list.append(tx)
                        except ValidationError:
                            pass
            elif "fecha" in data and "concepto" in data:
                try:
                    tx_list.append(Transaccion.model_validate(data))
                except ValidationError:
                    pass

        elif isinstance(data, list):
            for item in data:
                if isinstance(item, dict):
                    try:
                        tx_list.append(Transaccion.model_validate(item))
                    except ValidationError:
                        pass

        return tx_list

    except json.JSONDecodeError:
        pass

    # 6. Fallback: Heuristic extraction of individual transaction dictionaries
    salvaged_txs: List[Transaccion] = []
    dict_patterns = re.findall(r"\{[^{}]*\"concepto\"[^{}]*\}", candidate)
    for dict_str in dict_patterns:
        try:
            item = json.loads(dict_str)
            tx = Transaccion.model_validate(item)
            salvaged_txs.append(tx)
        except Exception:
            continue

    return salvaged_txs


def extract_transactions_with_ollama(
    text_content: str,
    base_url: str = "http://localhost:11434",
    model: str = "gemma4:12b",
    num_ctx: int = 16384,
    timeout_seconds: float = 180.0
) -> List[Transaccion]:
    """
    Sends document markdown/text to Ollama using robust table-aware chunking and Pydantic validation.
    
    Architectural Highlights:
    1. Table Whitespace Compaction: Strips Docling TableFormer whitespace padding.
    2. Bounded Chunking: Preserves multi-row table headers while bounding rows per chunk (<=14 rows)
       to prevent reasoning model token traps.
    3. Fast Pre-Flight Filtering: Bypasses non-financial disclaimer blocks to reduce inference time by >70%.
    4. Temperature 0.7 & Free-Form Thinking: Prevents greedy repetitive loops at temp 0.0 and grammar deadlocks.
    5. Robust Pydantic Parsing: Parses and validates JSON responses with graceful recovery.
    """
    clean_url = base_url.rstrip("/")
    compacted_text = compact_markdown_tables(text_content)
    all_chunks = chunk_text(compacted_text, max_chunk_chars=1800, max_table_rows=6)

    # Filter candidate chunks containing financial transactions
    candidate_chunks = [c for c in all_chunks if chunk_has_transaction_rows(c)]
    if not candidate_chunks:
        return []

    statement_year = extract_statement_year(text_content)

    print(
        f"[Ollama] Analizando {len(candidate_chunks)} fragmento(s) financiero(s) "
        f"(de {len(all_chunks)} totales, {len(all_chunks) - len(candidate_chunks)} omitidos por no contener transacciones)..."
    )

    all_transactions: List[Transaccion] = []
    prev_chunk_keys = set()

    with httpx.Client(timeout=timeout_seconds) as client:
        for chunk_idx, chunk in enumerate(candidate_chunks):
            if not chunk.strip():
                continue

            user_prompt = ""
            if statement_year:
                user_prompt += f"Contexto del documento: Año del estado de cuenta = {statement_year}.\n\n"
            user_prompt += (
                f"Analiza la siguiente tabla o fragmento del estado de cuenta y extrae las transacciones financieras individuales:\n\n"
                f"```text\n{chunk}\n```"
            )

            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ],
                "stream": False,
                "options": {
                    "temperature": 0.7,
                    "num_ctx": num_ctx,
                    "num_predict": 8192
                }
            }

            max_retries = 3
            attempt = 0
            success = False
            last_err = None

            while attempt < max_retries and not success:
                attempt += 1
                try:
                    response = client.post(f"{clean_url}/api/chat", json=payload)
                    response.raise_for_status()
                    data = response.json()
                    msg = data.get("message", {})
                    raw_message_content = msg.get("content", "")
                    thinking_content = msg.get("thinking", "")

                    # Parse and validate with fault-tolerant cleaner
                    chunk_txs = clean_and_parse_llm_json(raw_message_content, thinking_content)
                    print(f"[Ollama] Fragmento {chunk_idx + 1}/{len(candidate_chunks)}: {len(chunk_txs)} transacciones extraídas.")

                    current_chunk_keys = set()
                    for tx in chunk_txs:
                        # Normalize date with statement year fallback
                        tx.fecha = normalize_spanish_date(tx.fecha, default_year=statement_year)
                        if tx.importe <= 0.001:
                            continue
                        desc_clean = tx.descripcion.strip().lower() if tx.descripcion else ""
                        key = (tx.fecha, tx.concepto.strip().lower(), round(tx.importe, 2), tx.tipo, desc_clean)

                        # Adjacent chunk deduplication: filters out rows split/repeated across chunk boundaries,
                        # while preserving legitimate same-day twin transactions within the current chunk
                        if key in prev_chunk_keys:
                            continue
                        current_chunk_keys.add(key)
                        all_transactions.append(tx)

                    prev_chunk_keys = current_chunk_keys
                    success = True

                except (httpx.ConnectError, httpx.TimeoutException) as conn_err:
                    last_err = conn_err
                    if attempt < max_retries:
                        backoff = 1.5 * attempt
                        print(f"[Ollama] Conexión/Timeout en fragmento {chunk_idx + 1}. Reintento {attempt}/{max_retries} en {backoff}s...")
                        time.sleep(backoff)
                    else:
                        print(f"[Ollama] Falló conexión tras {max_retries} reintentos en fragmento {chunk_idx + 1}: {conn_err}")
                except httpx.HTTPStatusError as e:
                    last_err = e
                    # Retry on 5xx or rate limit 429
                    if e.response.status_code in (429, 500, 502, 503, 504) and attempt < max_retries:
                        backoff = 2.0 * attempt
                        print(f"[Ollama] Error HTTP {e.response.status_code} en fragmento {chunk_idx + 1}. Reintento {attempt}/{max_retries} en {backoff}s...")
                        time.sleep(backoff)
                    else:
                        raise RuntimeError(
                            f"Error de Ollama ({e.response.status_code}): {e.response.text}"
                        ) from e
                except Exception as e:
                    last_err = e
                    print(f"[Advertencia] Fragmento {chunk_idx + 1}/{len(candidate_chunks)} error de análisis: {str(e)}")
                    if attempt < max_retries:
                        backoff = 1.5 * attempt
                        time.sleep(backoff)
                    else:
                        raise RuntimeError(f"Error en fragmento {chunk_idx + 1} de {len(candidate_chunks)}: {str(e)}") from e

            if not success:
                raise RuntimeError(
                    f"Error de extracción en Ollama en fragmento {chunk_idx + 1} tras {max_retries} intentos: {str(last_err)}"
                ) from last_err

    print(f"[Ollama] Extracción finalizada: {len(all_transactions)} transacciones identificadas.")
    return all_transactions

