def clean_and_parse_llm_json(raw_content: str, thinking_content: str = "") -> List[Transaccion]:
    """
    Robust JSON parser for local LLM structured outputs.
    Handles:
    - Empty or whitespace responses (returns empty list).
    - Reasoning model thinking tokens (<think>...</think> or separate thinking field).
    - Markdown code fences (```json ... ```).
    - Malformed responses or trailing text.
    """
    candidate = (raw_content or "").strip()

    # 1. If content is empty, check if JSON was emitted inside thinking
    if not candidate and thinking_content:
        match_think = re.search(r"(\{[\s\S]*\"transacciones\"[\s\S]*\})", thinking_content)
        if match_think:
            candidate = match_think.group(1).strip()

    if not candidate:
        return []

    # 2. Strip <think>...</think> tags if present in main content
    candidate = re.sub(r"<think>[\s\S]*?</think>", "", candidate).strip()

    # 3. Strip Markdown code blocks if present
    if "```" in candidate:
        code_block_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", candidate)
        if code_block_match:
            candidate = code_block_match.group(1).strip()

    # 4. Extract outermost JSON object { ... } or array [ ... ]
    obj_match = re.search(r"(\{[\s\S]*\})", candidate)
    if obj_match:
        candidate = obj_match.group(1).strip()
    else:
        arr_match = re.search(r"(\[[\s\S]*\])", candidate)
        if arr_match:
            candidate = arr_match.group(1).strip()

    # 5. Attempt direct JSON parsing
    try:
        data = json.loads(candidate)
        tx_list: List[Transaccion] = []

        if isinstance(data, dict):
            if "transacciones" in data and isinstance(data["transacciones"], list):
                for item in data["transacciones"]:
                    if isinstance(item, dict):
                        try:
                            tx = Transaccion.model_validate(item)
                            tx_list.append(tx)
                        except ValidationError:
                            pass
            elif "fecha" in data and "concepto" in data:
                try:
                    tx_list.append(Transaccion.model_validate(data))
                except ValidationError:
                    pass

        elif isinstance(data, list):
            for item in data:
                if isinstance(item, dict):
                    try:
                        tx_list.append(Transaccion.model_validate(item))
                    except ValidationError:
                        pass

        return tx_list

    except json.JSONDecodeError:
        pass

    # 6. Fallback: Heuristic extraction of individual transaction dictionaries
    salvaged_txs: List[Transaccion] = []
    dict_patterns = re.findall(r"\{[^{}]*\"concepto\"[^{}]*\}", candidate)
    for dict_str in dict_patterns:
        try:
            item = json.loads(dict_str)
            tx = Transaccion.model_validate(item)
            salvaged_txs.append(tx)
        except Exception:
            continue

    return salvaged_txs


def clean_description(desc: str) -> str:
    """Normalizes description by trimming whitespace and lowercasing."""
    if not desc:
        return ""
    return " ".join(desc.strip().lower().split())


def extract_explicit_bank_reference(text: str) -> Optional[str]:
    """
    Extracts an explicit bank reference, tracking code, or authorization folio if present.
    Examples:
    - 'REF: 12345678' -> '12345678'
    - 'FOLIO: ABC-99' -> 'abc-99'
    - 'AUT: 554433'   -> '554433'
    - 'SPEI: 014028'  -> '014028'
    """
    if not text:
        return None
    match = re.search(
        r"\b(?:ref(?:erencia)?|folio|aut(?:orizacion)?|spei|rastreo)[^\w\d]{0,5}([a-z0-9\-]{4,40})\b",
        text,
        re.IGNORECASE
    )
    if match:
        return match.group(1).lower()
    return None


def deduplicate_within_chunk(transactions: List[Transaccion]) -> List[Transaccion]:
    """
    Conserves identical transactions within the same chunk (e.g. repeated purchases at the same store on the same day)
    UNLESS they possess the exact same explicit bank reference/folio.
    """
    seen_refs = set()
    result = []
    for tx in transactions:
        ref = extract_explicit_bank_reference(tx.descripcion)
        if ref:
            ref_key = (tx.fecha, round(float(tx.importe), 2), ref)
            if ref_key in seen_refs:
                continue
            seen_refs.add(ref_key)
        result.append(tx)
    return result


def deduplicate_adjacent_chunks(
    chunk_i_txs: List[Transaccion],
    chunk_next_txs: List[Transaccion],
    boundary_window: int = 5
) -> List[Transaccion]:
    """
    Deduplicates transactions between adjacent chunks (chunk_i, chunk_i+1):
    - Compares only the last `boundary_window` movements of chunk_i against the first `boundary_window` of chunk_i+1
      using the tuple: (fecha, round(importe, 2), descripcion_limpia).
    - Preserves legitimate twin transactions within the chunks unless they share an explicit identical bank reference.

    Returns:
        List[Transaccion]: The filtered transactions from chunk_next_txs that were not repeated from chunk_i boundary.
    """
    if not chunk_i_txs or not chunk_next_txs:
        return deduplicate_within_chunk(chunk_next_txs)

    # Clean the tail of chunk_i
    tail = chunk_i_txs[-boundary_window:]
    tail_keys = {
        (tx.fecha, round(float(tx.importe), 2), clean_description(tx.descripcion))
        for tx in tail
    }

    # Filter out boundary duplicates from the head of chunk_next_txs
    filtered_next: List[Transaccion] = []
    for idx, tx in enumerate(chunk_next_txs):
        key = (tx.fecha, round(float(tx.importe), 2), clean_description(tx.descripcion))
        if idx < boundary_window and key in tail_keys:
            # Overlapping boundary duplicate row from previous table chunk
            continue
        filtered_next.append(tx)

    # Within the remaining chunk_next_txs, deduplicate only identical bank references
    return deduplicate_within_chunk(filtered_next)


def deduplicate_all_chunks(
    chunks_transactions: List[List[Transaccion]],
    boundary_window: int = 5
) -> List[Transaccion]:
    """
    Processes a sequence of chunk transaction lists, applying intra-chunk preservation
    and adjacent-boundary deduplication across chunk_i and chunk_i+1.
    """
    if not chunks_transactions:
        return []

    accumulated: List[Transaccion] = deduplicate_within_chunk(chunks_transactions[0])
    for next_chunk in chunks_transactions[1:]:
        deduped_next = deduplicate_adjacent_chunks(accumulated, next_chunk, boundary_window=boundary_window)
        accumulated.extend(deduped_next)

    return accumulated


def extract_transactions_with_ollama(
    text_content: str,
    base_url: str = "http://localhost:11434",
    model: str = "gemma4:12b",
    num_ctx: int = 8192,
    timeout_seconds: float = 180.0
) -> List[Transaccion]:
    """
    Sends document markdown/text to Ollama using robust table-aware chunking and Pydantic validation.
    
    Architectural Highlights:
    1. Table Whitespace Compaction: Strips Docling TableFormer whitespace padding.
    2. Bounded Chunking: Preserves multi-row table headers while bounding rows per chunk (<=14 rows)
       to prevent reasoning model token traps.
    3. Fast Pre-Flight Filtering: Bypasses non-financial disclaimer blocks to reduce inference time by >70%.
    4. Temperature 0.7 & Free-Form Thinking: Prevents greedy repetitive loops at temp 0.0 and grammar deadlocks.
    5. Robust Pydantic Parsing: Parses and validates JSON responses with graceful recovery.
    """
    clean_url = base_url.rstrip("/")
    compacted_text = compact_markdown_tables(text_content)
    all_chunks = chunk_text(compacted_text, max_chunk_chars=1800, max_table_rows=6)

    # Filter candidate chunks containing financial transactions
    candidate_chunks = [c for c in all_chunks if chunk_has_transaction_rows(c)]
    if not candidate_chunks:
        return []

    statement_year = extract_statement_year(text_content)

    print(
        f"[Ollama] Analizando {len(candidate_chunks)} fragmento(s) financiero(s) "
        f"(de {len(all_chunks)} totales, {len(all_chunks) - len(candidate_chunks)} omitidos por no contener transacciones)..."
    )

    all_transactions: List[Transaccion] = []
    prev_chunk_keys = set()

    with httpx.Client(timeout=timeout_seconds) as client:
        for chunk_idx, chunk in enumerate(candidate_chunks):
            if not chunk.strip():
                continue

            user_prompt = ""
            if statement_year:
                user_prompt += f"Contexto del documento: Año del estado de cuenta = {statement_year}.\n\n"
            user_prompt += (
                f"Analiza la siguiente tabla o fragmento del estado de cuenta y extrae las transacciones financieras individuales:\n\n"
                f"```text\n{chunk}\n```"
            )

            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ],
                "stream": False,
                "format": "json",
                "options": {
                    "temperature": 0.0,
                    "num_ctx": 8192,
                    "num_predict": 8192
                }
            }

            max_retries = 2
            attempt = 0
            success = False
            last_err = None
            chunk_txs: List[Transaccion] = []
            raw_message_content = ""
            thinking_content = ""

            while attempt <= max_retries and not success:
                attempt += 1
                try:
                    response = client.post(f"{clean_url}/api/chat", json=payload)
                    response.raise_for_status()
                    data = response.json()
                    msg = data.get("message", {})
                    raw_message_content = msg.get("content", "")
                    thinking_content = msg.get("thinking", "")

                    # Strict JSON parsing first
                    try:
                        chunk_txs = parse_strict_llm_json(raw_message_content)
                        if chunk_txs or not raw_message_content.strip():
                            success = True
                        else:
                            raise ValueError("Strict JSON parsing returned empty transaction list")
                    except Exception as json_err:
                        last_err = json_err
                        if attempt <= max_retries:
                            print(f"[Ollama] Error al parsear JSON en fragmento {chunk_idx + 1} (intento {attempt}/{max_retries + 1}). Reintentando...")
                            time.sleep(1.0)
                            continue
                        else:
                            # Invoke heuristic fallback after max retries
                            print(f"[Ollama] Invocando fallback heurístico en fragmento {chunk_idx + 1} tras agotar reintentos de parseo...")
                            chunk_txs = parse_heuristic_fallback(raw_message_content, thinking_content)
                            success = True

                except (httpx.ConnectError, httpx.TimeoutException) as conn_err:
                    last_err = conn_err
                    if attempt <= max_retries:
                        backoff = 1.5 * attempt
                        print(f"[Ollama] Timeout o error de conexión en fragmento {chunk_idx + 1} (intento {attempt}/{max_retries + 1}). Reintentando en {backoff}s...")
                        time.sleep(backoff)
                    else:
                        print(f"[Ollama] Falló conexión tras {max_retries} reintentos en fragmento {chunk_idx + 1}: {conn_err}")
                        raise RuntimeError(
                            f"Timeout/Error de conexión en Ollama en fragmento {chunk_idx + 1} tras {max_retries} reintentos: {conn_err}"
                        ) from conn_err
                except httpx.HTTPStatusError as e:
                    last_err = e
                    if e.response.status_code in (429, 500, 502, 503, 504) and attempt <= max_retries:
                        backoff = 2.0 * attempt
                        print(f"[Ollama] Error HTTP {e.response.status_code} en fragmento {chunk_idx + 1}. Reintento {attempt}/{max_retries + 1} en {backoff}s...")
                        time.sleep(backoff)
                    else:
                        raise RuntimeError(
                            f"Error de Ollama ({e.response.status_code}): {e.response.text}"
                        ) from e
                except Exception as e:
                    last_err = e
                    if attempt <= max_retries:
                        time.sleep(1.0)
                    else:
                        chunk_txs = parse_heuristic_fallback(raw_message_content, thinking_content)
                        success = True

            if not success:
                chunk_txs = parse_heuristic_fallback(raw_message_content, thinking_content)

            # Normalize date with statement year fallback
            for tx in chunk_txs:
                tx.fecha = normalize_spanish_date(tx.fecha, default_year=statement_year)

            valid_chunk_txs = [tx for tx in chunk_txs if tx.importe > 0.001]
            deduped = deduplicate_adjacent_chunks(all_transactions, valid_chunk_txs, boundary_window=5)
            all_transactions.extend(deduped)

    print(f"[Ollama] Extracción finalizada: {len(all_transactions)} transacciones identificadas.")
    return all_transactions

