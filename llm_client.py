DATE_PATTERN = re.compile(
    r"\b(?:\d{1,2}[-/\s](?:ene|feb|mar|abr|may|jun|jul|ago|sep|oct|nov|dic|[a-z]{3}|\d{1,2})[-/\s]\d{2,4}|\d{4}[-/\s]\d{1,2}[-/\s]\d{1,2})\b",
    re.IGNORECASE
)
MONEY_PATTERN = re.compile(r"(?:\$\s*[\d,]+\.\d{2}|[\d,]+\.\d{2})")


def compact_markdown_tables(text: str) -> str:
    """
    Compacts excessive whitespace padding inside markdown table rows generated by TableFormer/Docling.
    Reduces line lengths from ~600 chars to ~60 chars while maintaining table structure.
    """
    lines = text.split("\n")
    cleaned_lines = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [re.sub(r"[ \t]+", " ", cell).strip() for cell in stripped.split("|")]
            cleaned_lines.append(" | ".join(cells).strip())
        else:
            cleaned_lines.append(line)
    return "\n".join(cleaned_lines)


def is_table_data_row(line: str) -> bool:
    stripped = line.strip()
    return stripped.startswith("|") and stripped.endswith("|") and bool(
        DATE_PATTERN.search(stripped) and MONEY_PATTERN.search(stripped)
    )


def chunk_has_transaction_rows(text: str) -> bool:
    """
    Fast pre-flight regex check to identify if a text chunk contains candidate financial rows.
    Allows non-financial blocks (e.g. legal disclaimers, insurance ads) to be bypassed with 0 LLM latency.
    Supports both pipe-delimited tables and multi-line structured XML/text records.
    """
    for line in text.split("\n"):
        stripped = line.strip()
        if "|" in stripped:
            if DATE_PATTERN.search(stripped) and MONEY_PATTERN.search(stripped):
                return True
        elif DATE_PATTERN.search(stripped) and MONEY_PATTERN.search(stripped):
            return True

    # Multi-line inspection for structured XML or key-value representations
    if DATE_PATTERN.search(text) and MONEY_PATTERN.search(text):
        financial_cues = [
            "cargo", "abono", "deposito", "retiro", "pago", "compra",
            "transferencia", "importe", "monto", "total", "saldo",
            "subtotal", "iva", "spei", "$", "mxn", "usd", "concepto", "movimiento"
        ]
        text_lower = text.lower()
        if any(cue in text_lower for cue in financial_cues):
            return True

    return False



def check_ollama_connection(base_url: str = "http://localhost:11434") -> Tuple[bool, str, List[str]]:
    """
    Checks if Ollama is running locally and retrieves the list of installed models.
    Returns:
        (is_connected: bool, status_message: str, installed_models: List[str])
    """
    clean_url = base_url.rstrip("/")
    try:
        with httpx.Client(timeout=3.0) as client:
            resp = client.get(f"{clean_url}/api/tags")
            if resp.status_code == 200:
                data = resp.json()
                models = [m.get("name", "") for m in data.get("models", [])]
                return True, f"Conexión exitosa a Ollama ({len(models)} modelo(s) disponibles)", models
            return False, f"Ollama respondió con código de error {resp.status_code}", []
    except httpx.ConnectError:
        return False, "No se pudo conectar a Ollama. Asegúrate de que el servicio esté activo en localhost:11434.", []
    except Exception as e:
        return False, f"Error al verificar Ollama: {str(e)}", []


def chunk_text(text: str, max_chunk_chars: int = 1800, max_table_rows: int = 6) -> List[str]:
    """
    Splits long Markdown or extracted document text into logical, table-aware chunks.
    Preserves multi-row table headers (title, separator, column names) across chunk boundaries
    and limits the number of transaction data rows per chunk to avoid reasoning loop traps in LLMs.
    """
    if not text.strip():
        return [text] if text else []

    lines = text.split("\n")
    chunks = []
    current_chunk = []
    current_length = 0
    active_table_headers = []
    table_rows_in_chunk = 0
    in_table = False

    for line in lines:
        stripped = line.strip()
        is_table_line = stripped.startswith("|") and stripped.endswith("|")

        if is_table_line:
            is_data = is_table_data_row(stripped)

            # If starting a new table or entering one with a different column count, reset headers
            if not in_table or (active_table_headers and stripped.count("|") != active_table_headers[0].count("|")):
                in_table = True
                active_table_headers = []
                table_rows_in_chunk = 0

            # Collect table header rows before data rows start
            if not is_data and table_rows_in_chunk == 0 and len(active_table_headers) < 4:
                active_table_headers.append(stripped)
            elif is_data:
                table_rows_in_chunk += 1
        else:
            if in_table and not stripped:
                in_table = False
                active_table_headers = []
                table_rows_in_chunk = 0

        line_len = len(line) + 1
        exceeds_chars = (current_length + line_len > max_chunk_chars)
        exceeds_rows = (table_rows_in_chunk > max_table_rows)

        if (exceeds_chars or exceeds_rows) and current_chunk:
            chunks.append("\n".join(current_chunk))
            if in_table and active_table_headers:
                current_chunk = list(active_table_headers) + [line]
                current_length = sum(len(h) + 1 for h in active_table_headers) + line_len
                table_rows_in_chunk = 1 if is_table_data_row(stripped) else 0
            else:
                current_chunk = [line]
                current_length = line_len
                table_rows_in_chunk = 1 if is_table_data_row(stripped) else 0
        else:
            current_chunk.append(line)
            current_length += line_len

    if current_chunk:
        chunks.append("\n".join(current_chunk))

    return chunks


